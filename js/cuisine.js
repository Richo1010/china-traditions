let currentTag = "Все";

document.addEventListener("DOMContentLoaded", () => {
  renderFilters();
  renderDishes();

  const modal = document.getElementById("recipeModal");
  modal.addEventListener("click", e => {
    if (e.target === modal || e.target.closest(".modal-close")) closeRecipe();
  });
  document.addEventListener("keydown", e => {
    if (e.key === "Escape") closeRecipe();
  });
});

function renderFilters() {
  const tags = ["Все", ...new Set(DISHES.flatMap(d => d.tags))];
  const bar = document.getElementById("dishFilter");
  bar.innerHTML = tags.map(t =>
    `<button class="chip${t === currentTag ? " active" : ""}" data-tag="${t}">${t}</button>`
  ).join("");
  bar.querySelectorAll(".chip").forEach(btn => {
    btn.addEventListener("click", () => {
      currentTag = btn.dataset.tag;
      renderFilters();
      renderDishes();
    });
  });
}

function renderDishes() {
  const list = DISHES.filter(d => currentTag === "Все" || d.tags.includes(currentTag));
  const grid = document.getElementById("dishes");
  grid.innerHTML = list.map((d, i) => `
    <div class="card dish">
      <div class="photo" data-img="assets/img/dish-${d.id}.jpg" data-glyph="${d.glyph}"></div>
      <div class="card-body">
        <div class="card-title"><span class="num">${i + 1}</span><h3>${d.name}</h3></div>
        <div><span class="cn">${d.cn}</span> · <span class="pinyin">${d.py}</span></div>
        <div class="meta"><span>⏱ ${d.time}</span><span>◆ ${d.level}</span><span>🏮 ${d.tags.join(", ")}</span></div>
        <button class="btn" data-id="${d.id}">Рецепт</button>
      </div>
    </div>`).join("");
  grid.querySelectorAll(".btn").forEach(btn => btn.addEventListener("click", () => openRecipe(btn.dataset.id)));
  initPhotos();
}

function openRecipe(id) {
  const d = DISHES.find(x => x.id === id);
  const modal = document.getElementById("recipeModal");
  modal.querySelector(".modal-content").innerHTML = `
    <span class="eyebrow">${d.tags.join(" · ")}</span>
    <h2 style="margin-bottom:4px">${d.name}</h2>
    <div style="margin-bottom:12px"><span class="cn" style="font-size:1.3rem">${d.cn}</span> · <span class="pinyin">${d.py}</span></div>
    <p>${d.about}</p>
    <div class="recipe-cols">
      <div>
        <h3>Ингредиенты</h3>
        <ul>${d.ingredients.map(x => `<li>${x}</li>`).join("")}</ul>
      </div>
      <div>
        <h3>Приготовление</h3>
        <ol>${d.steps.map(x => `<li>${x}</li>`).join("")}</ol>
      </div>
    </div>`;
  modal.classList.add("show");
  document.body.style.overflow = "hidden";
  modal.querySelector(".modal-close").focus();
}

function closeRecipe() {
  document.getElementById("recipeModal").classList.remove("show");
  document.body.style.overflow = "";
}
