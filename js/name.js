const VOWELS = "аеёиоуыэюя";
const HISSING = "жшчщц";

/* Разбивает имя на слоги и подбирает иероглифы */
function transcribe(word) {
  const w = word.toLowerCase().replace(/ё/g, "ё").replace(/[ьъ]/g, "");
  if (KNOWN_NAMES[w]) return KNOWN_NAMES[w];

  const result = [];
  const push = s => { if (SYLLABLES[s]) result.push(SYLLABLES[s]); };

  for (let i = 0; i < w.length; i++) {
    const c = w[i];
    const next = w[i + 1];

    if (VOWELS.includes(c)) {
      push(c);
      continue;
    }
    if (c === "й") {
      /* «й» после гласной в конце слова обычно не передаётся */
      if (i === 0 || !VOWELS.includes(w[i - 1])) push("й");
      continue;
    }
    if (!SYLLABLES[c]) continue;
    /* удвоенная согласная передаётся один раз */
    if (next === c) continue;

    if (next && VOWELS.includes(next)) {
      if ((next === "я" || next === "ю") && !HISSING.includes(c)) {
        push(c + "и");
        push(next);
      } else if (next === "я") {
        push(c + "а");
      } else if (next === "ю") {
        push(c + "у");
      } else {
        push(c + next);
      }
      i++;
    } else {
      push(c);
    }
  }
  return result.map(ch => [ch, PINYIN[ch] || ""]);
}

document.addEventListener("DOMContentLoaded", () => {
  const form = document.getElementById("nameForm");
  const input = document.getElementById("nameInput");
  const out = document.getElementById("nameResult");

  form.addEventListener("submit", e => {
    e.preventDefault();
    const name = input.value.trim().split(/\s+/)[0] || "";
    if (!/^[а-яё-]+$/i.test(name)) {
      showToast("Введите имя русскими буквами");
      return;
    }
    const chars = transcribe(name.replace(/-/g, ""));
    if (chars.length === 0) {
      showToast("Не удалось подобрать иероглифы");
      return;
    }
    const pretty = name[0].toUpperCase() + name.slice(1).toLowerCase();
    out.innerHTML = `
      <div class="name-scroll">
        ${chars.map(([ch, py]) => `<div class="ch">${ch}<small>${py}</small></div>`).join("")}
        <div class="stamp">名</div>
      </div>
      <p style="margin-top:18px"><b>${pretty}</b> — <span class="cn">${chars.map(c => c[0]).join("")}</span>
      (<span class="pinyin">${chars.map(c => c[1]).join(" ")}</span>)</p>
      <p class="note" style="text-align:left;max-width:640px;margin:0 auto">Иностранные имена в Китае записывают иероглифами по звучанию, а не по смыслу. Для известных имён используются принятые в Китае варианты, для остальных — подбор по слогам, поэтому результат приблизительный.</p>`;
    out.classList.remove("show");
    void out.offsetWidth;
    out.classList.add("show");
  });
});
