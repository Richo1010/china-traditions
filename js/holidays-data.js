/* Ближайшая будущая дата праздника (или null) */
function nextDate(holiday, from = new Date()) {
  const today = new Date(from.getFullYear(), from.getMonth(), from.getDate());
  for (const s of holiday.dates) {
    const d = new Date(s + "T00:00:00");
    if (d >= today) return d;
  }
  return null;
}

/* Ближайший праздник из всех */
function nearestHoliday(from = new Date()) {
  let best = null;
  for (const h of HOLIDAYS) {
    const d = nextDate(h, from);
    if (d && (!best || d < best.date)) best = { holiday: h, date: d };
  }
  return best;
}

/* Сколько дней до даты */
function daysUntil(date, from = new Date()) {
  const today = new Date(from.getFullYear(), from.getMonth(), from.getDate());
  return Math.round((date - today) / 86400000);
}

/* Склонение: 1 день, 2 дня, 5 дней */
function plural(n, one, few, many) {
  const n10 = n % 10;
  const n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return few;
  return many;
}

const MONTHS_GEN = ["января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря"];

function formatDate(d) {
  return d.getDate() + " " + MONTHS_GEN[d.getMonth()] + " " + d.getFullYear();
}
