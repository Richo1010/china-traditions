/* Знаки одного «треугольника» лучше всего ладят друг с другом */
const TRINES = [[0, 4, 8], [1, 5, 9], [2, 6, 10], [3, 7, 11]];

/* Год по китайскому календарю для даты рождения */
function lunarYear(date) {
  let y = date.getFullYear();
  const idx = y - NEW_YEAR_FROM;
  if (idx >= 0 && idx < NEW_YEAR_DATES.length) {
    const md = NEW_YEAR_DATES[idx];
    const ny = new Date(y, +md.slice(0, 2) - 1, +md.slice(2));
    if (date < ny) y -= 1;
  }
  return y;
}

function zodiacFor(date) {
  const y = lunarYear(date);
  const animalIndex = ((y - 4) % 12 + 12) % 12;
  const elementIndex = Math.floor((((y - 4) % 10 + 10) % 10) / 2);
  const element = ELEMENTS[[2, 3, 4, 0, 1][elementIndex]];
  const yin = y % 2 === 1;
  return { year: y, animalIndex, animal: ANIMALS[animalIndex], element, yin };
}

document.addEventListener("DOMContentLoaded", () => {
  const form = document.getElementById("zodiacForm");
  const input = document.getElementById("birth");
  const out = document.getElementById("zodiacResult");
  const ring = document.getElementById("zodiacRing");

  ring.innerHTML = ANIMALS.map((a, i) => `<div data-i="${i}"><b>${a.cn}</b>${a.name}</div>`).join("");

  form.addEventListener("submit", e => {
    e.preventDefault();
    if (!input.value) {
      showToast("Укажите дату рождения");
      return;
    }
    const date = new Date(input.value + "T00:00:00");
    const z = zodiacFor(date);
    const friends = TRINES.find(t => t.includes(z.animalIndex))
      .filter(i => i !== z.animalIndex)
      .map(i => ANIMALS[i].name);

    const note = z.year !== date.getFullYear()
      ? `<p class="note">Вы родились до Праздника весны ${date.getFullYear()} года, поэтому по китайскому календарю ваш год — ${z.year}-й.</p>`
      : "";

    out.innerHTML = `
      <div class="zodiac-result">
        <div class="seal">${z.animal.cn}</div>
        <div>
          <span class="eyebrow">${z.year} год</span>
          <h2 style="margin-bottom:4px">${z.animal.name} · стихия ${z.element.name}</h2>
          <div><span class="cn">${z.element.cn}${z.animal.cn}</span> · <span class="pinyin">${z.animal.py}</span></div>
          <div class="tags">
            ${z.animal.traits.map(t => `<span class="tag">${t}</span>`).join("")}
            <span class="tag">${z.yin ? "Инь 阴" : "Ян 阳"}</span>
          </div>
          <p>${z.animal.text}</p>
          <p>Стихия <b>${z.element.name}</b> (${z.element.cn}) добавляет характеру ${z.element.text}.</p>
          <p style="margin:0">Лучшая совместимость: <b>${friends.join(" и ")}</b>.</p>
          ${note}
        </div>
      </div>`;
    out.classList.remove("show");
    void out.offsetWidth;
    out.classList.add("show");

    ring.querySelectorAll("div").forEach(d => d.classList.toggle("current", +d.dataset.i === z.animalIndex));
  });
});
